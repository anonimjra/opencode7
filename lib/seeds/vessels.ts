import type { Vessel, Waypoint } from '@/types/supply-chain';

function iso(daysOffset: number, hour = 0): string {
  const base = new Date('2024-06-10T06:00:00.000Z');
  const shifted = new Date(base.getTime() + daysOffset * 86_400_000 + hour * 3_600_000);
  return shifted.toISOString();
}

function wp(
  name: string,
  lat: number,
  lng: number,
  daysOffset: number,
  status: Waypoint['status'],
  actualDaysOffset?: number,
): Waypoint {
  return {
    name,
    lat,
    lng,
    estimatedArrival: iso(daysOffset),
    actualArrival: actualDaysOffset !== undefined ? iso(actualDaysOffset) : undefined,
    status,
  };
}

